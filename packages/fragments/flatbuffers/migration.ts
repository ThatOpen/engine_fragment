/* eslint-disable import/no-extraneous-dependencies */
import { execFileSync } from "node:child_process";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import prettier from "prettier";
import { Copier } from "../src/Migrations/src/layout/copier";
import type { SchemaDescriptor } from "../src/Migrations/src/layout/descriptor";
import { conforms, describeSchema } from "./migration/describe";
import { SchemaDiff, diffSchemas } from "./migration/diff";
import { emitTypes } from "./migration/emit-types";

// yarn migration:new <slug>   a directory for a change to fragments files
// yarn migration:check        what CI runs: is every schema change covered?
// yarn migration:sync         rewrite the generated files

const here = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(here, "..");
const migrations = path.join(packageRoot, "src", "Migrations");
const list = path.join(migrations, "list");
const currentSchema = path.join(here, "index.fbs");

const DIRECTORY = /^(\d{14})_([a-z0-9][a-z0-9-]*)$/;
const HEADER = "// Generated by `yarn migration:new`. Do not edit.";

interface Step {
  id: string;
  slug: string;
  dir: string;
  /** The layout from this step on, when the step changed the schema. */
  schema?: SchemaDescriptor;
  hasMigration: boolean;
}

/** `diff.json`: the diff, plus what flatc says about the same change. */
interface StoredDiff extends SchemaDiff {
  from: string;
  to: string;
  /** Whether `flatc --conform` accepts the new schema as an evolution of the old. */
  conforms: boolean;
}

function readSteps(): Step[] {
  if (!fs.existsSync(list)) {
    return [];
  }
  const steps: Step[] = [];
  for (const name of fs.readdirSync(list).sort()) {
    const dir = path.join(list, name);
    if (!fs.statSync(dir).isDirectory()) continue;
    const match = DIRECTORY.exec(name);
    if (!match) {
      throw new Error(
        `${name}: a migration directory is named <YYYYMMDDHHmmss>_<slug>.`,
      );
    }
    const schemaFile = path.join(dir, "schema.json");
    steps.push({
      id: match[1],
      slug: match[2],
      dir,
      schema: fs.existsSync(schemaFile)
        ? JSON.parse(fs.readFileSync(schemaFile, "utf8"))
        : undefined,
      hasMigration: fs.existsSync(path.join(dir, "migration.ts")),
    });
  }
  return steps;
}

async function format(file: string, source: string) {
  const config = await prettier.resolveConfig(file);
  return prettier.format(source, { ...config, filepath: file });
}

/**
 * JSON with every object of plain values on one line, so a descriptor reads
 * one field per line. Prettier then only breaks the lines that are too long,
 * which keeps the files as `yarn format` would leave them.
 */
function stringify(value: unknown, indent = ""): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }
  const plain = (item: unknown) => item === null || typeof item !== "object";
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    if (value.every(plain)) {
      return `[${value.map((item) => JSON.stringify(item)).join(", ")}]`;
    }
    const items = value.map((item) => inner + stringify(item, inner));
    return `[\n${items.join(",\n")}\n${indent}]`;
  }
  const entries = Object.entries(value).filter(
    ([, item]) => item !== undefined,
  );
  if (entries.length === 0) {
    return "{}";
  }
  if (entries.every(([, item]) => plain(item))) {
    const fields = entries.map(
      ([key, item]) => `${JSON.stringify(key)}: ${JSON.stringify(item)}`,
    );
    return `{ ${fields.join(", ")} }`;
  }
  const fields = entries.map(
    ([key, item]) =>
      `${inner}${JSON.stringify(key)}: ${stringify(item, inner)}`,
  );
  return `{\n${fields.join(",\n")}\n${indent}}`;
}

function json(value: unknown, file = "file.json") {
  return format(file, stringify(value));
}

/** Every generated file that derives from the directories, with its content. */
async function generate(steps: Step[]) {
  const files = new Map<string, string>();
  const rewrites = new Set<string>();

  let previous: Step | undefined;
  for (const step of steps) {
    if (!step.schema) continue;
    if (previous?.schema) {
      const diff = diffSchemas(previous.schema, step.schema);
      const verdict = await conforms(
        path.join(previous.dir, "schema.fbs"),
        path.join(step.dir, "schema.fbs"),
      );
      const stored: StoredDiff = {
        from: previous.id,
        to: step.id,
        conforms: verdict.ok,
        ...diff,
      };
      const diffFile = path.join(step.dir, "diff.json");
      files.set(diffFile, await json(stored, diffFile));
      if (diff.rewrite) {
        rewrites.add(step.id);
      }
      if (diff.rewrite) {
        const file = path.join(step.dir, "types.ts");
        const types = emitTypes(previous.schema, step.schema, diff);
        files.set(file, await format(file, types));
      }
    }
    previous = step;
  }

  const imports: string[] = [];
  const entries: string[] = [];
  for (const step of steps) {
    const base = `./list/${path.basename(step.dir)}`;
    const parts = [`id: "${step.id}"`, `slug: "${step.slug}"`];
    if (step.schema) {
      imports.push(`import schema${step.id} from "${base}/schema.json";`);
      parts.push(`schema: schema${step.id} as SchemaDescriptor`);
    }
    if (rewrites.has(step.id)) {
      parts.push("rewrite: true");
    }
    if (step.hasMigration) {
      imports.push(`import migration${step.id} from "${base}/migration";`);
      parts.push(`migration: migration${step.id}`);
    }
    entries.push(`{ ${parts.join(", ")} },`);
  }
  const registry = path.join(migrations, "registry.ts");
  files.set(
    registry,
    await format(
      registry,
      [
        HEADER,
        `import type { SchemaDescriptor } from "./src/layout/descriptor";`,
        `import type { MigrationRegistry } from "./src/types";`,
        `import { UNSTAMPED_REVISION } from "./list/unstamped";`,
        ...imports,
        "",
        "/** Every change to fragments files this package knows, oldest first. */",
        "export const registry: MigrationRegistry = {",
        "  unstamped: UNSTAMPED_REVISION,",
        `  steps: [${entries.join("\n")}],`,
        "};",
      ].join("\n"),
    ),
  );

  const revision = path.join(migrations, "revision.ts");
  const latest = steps[steps.length - 1].id;
  files.set(
    revision,
    await format(
      revision,
      [
        HEADER,
        "",
        "/**",
        " * The revision of the files this package writes: the id of its newest",
        " * migration. Kept apart from the registry so that the writers can stamp it",
        " * without importing the migrations.",
        " */",
        `export const LATEST_REVISION = "${latest}";`,
      ].join("\n"),
    ),
  );

  return { files, rewrites };
}

function same(a: unknown, b: unknown) {
  return JSON.stringify(a) === JSON.stringify(b);
}

function write(file: string, content: string) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function relative(file: string) {
  return path.relative(packageRoot, file);
}

function timestamp() {
  return new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
}

function scaffoldLayout(diff: SchemaDiff) {
  if (diff.obligations.length === 0) {
    return [
      `import { defineMigration } from "../../src/define";`,
      "",
      "// The schema changed in a way the copier carries on its own, so there is",
      "// nothing to decide here. See diff.json.",
      "export default defineMigration({",
      `  title: "TODO: say what changed",`,
      "});",
    ].join("\n");
  }
  const handlers = diff.changes
    .filter((change) => change.obligation)
    .map((change) =>
      [
        `    // ${change.kind}: ${change.detail}`,
        `    "${change.path}": () => {`,
        `      throw new Error("TODO: decide ${change.path}");`,
        "    },",
      ].join("\n"),
    );
  return [
    `import { defineMigration } from "../../src/define";`,
    `import type { Handlers } from "./types";`,
    "",
    "// What this migration keeps about one file while it runs.",
    "type Ctx = {};",
    "",
    "export default defineMigration<Ctx, Handlers<Ctx>>({",
    `  title: "TODO: say what changed",`,
    "  // One handler per decision the schema change leaves open (see types.ts).",
    "  // A removed field returns `drop`, from the same module as defineMigration.",
    "  layout: {",
    ...handlers,
    "  },",
    "});",
  ].join("\n");
}

function scaffoldEdit() {
  return [
    `import { defineMigration } from "../../src/define";`,
    "",
    "export default defineMigration({",
    `  title: "TODO: say what changed",`,
    "  edit: () => {",
    `    throw new Error("TODO: return the requests that bring a file up to date");`,
    "  },",
    "});",
  ].join("\n");
}

function scaffoldTest(slug: string) {
  return [
    `import { test } from "vitest";`,
    "",
    `test.todo("${slug}: migrates a file that predates it");`,
  ].join("\n");
}

async function create(args: string[]) {
  const options: Record<string, string> = {};
  const positional: string[] = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i].startsWith("--")) {
      options[args[i].slice(2)] = args[++i];
    } else {
      positional.push(args[i]);
    }
  }
  const slug = positional[0];
  const id = options.id ?? timestamp();
  const name = `${id}_${slug}`;
  if (!slug || !DIRECTORY.test(name)) {
    throw new Error(
      "Usage: yarn migration:new <slug> [--id <YYYYMMDDHHmmss>] [--schema <file.fbs>]",
    );
  }
  const steps = readSteps();
  const last = steps[steps.length - 1];
  if (last && id <= last.id) {
    throw new Error(`${id} is not after the newest migration, ${last.id}.`);
  }

  // The schema is index.fbs unless a step is being written for a past one.
  const schemaFile = options.schema
    ? path.resolve(options.schema)
    : currentSchema;
  const schema = await describeSchema(schemaFile);
  const previous = [...steps].reverse().find((step) => step.schema);
  const changed = !same(previous?.schema, schema);

  const dir = path.join(list, name);
  const step: Step = { id, slug, dir, hasMigration: false };
  let scaffold: string | undefined;
  if (changed) {
    step.schema = schema;
    const schemaJson = path.join(dir, "schema.json");
    write(schemaJson, await json(schema, schemaJson));
    fs.copyFileSync(schemaFile, path.join(dir, "schema.fbs"));
    if (previous?.schema) {
      const diff = diffSchemas(previous.schema, schema);
      if (diff.rewrite) {
        scaffold = scaffoldLayout(diff);
      }
      for (const change of diff.changes) {
        const flags = [
          change.breaking ? "breaking" : "",
          change.obligation ? "needs a handler" : "",
        ].filter(Boolean);
        const suffix = flags.length > 0 ? ` (${flags.join(", ")})` : "";
        console.log(
          `  ${change.kind} ${change.path}: ${change.detail}${suffix}`,
        );
      }
    }
  } else {
    scaffold = scaffoldEdit();
  }
  if (scaffold) {
    const file = path.join(dir, "migration.ts");
    write(file, await format(file, scaffold));
    const test = path.join(dir, "migration.test.ts");
    write(test, await format(test, scaffoldTest(slug)));
    step.hasMigration = true;
  }

  const { files } = await generate([...steps, step]);
  for (const [file, content] of files) {
    write(file, content);
  }
  console.log(`Created ${relative(dir)}`);
  if (scaffold) {
    console.log(`Now write ${relative(path.join(dir, "migration.ts"))}`);
  } else if (previous) {
    console.log(
      "The schema only grew: files written before it need no migration.",
    );
  }
}

async function sync() {
  const { files } = await generate(readSteps());
  for (const [file, content] of files) {
    write(file, content);
  }
}

function idsOn(ref: string) {
  const repoRoot = execFileSync("git", ["rev-parse", "--show-toplevel"], {
    cwd: packageRoot,
    encoding: "utf8",
  }).trim();
  const prefix = `${path.relative(repoRoot, list)}/`;
  const out = execFileSync("git", ["ls-tree", "--name-only", ref, prefix], {
    cwd: repoRoot,
    encoding: "utf8",
  });
  return out
    .split("\n")
    .map((line) => DIRECTORY.exec(path.basename(line))?.[1])
    .filter((id): id is string => id !== undefined);
}

/**
 * Whether each migration decides everything its schema change leaves open.
 * The copier plans a whole copy before it touches a file and refuses a field
 * it cannot carry and has no handler for, so planning one with the handlers
 * of the migration is the check: no fixture needed, and it is the very code
 * that will run on a file. A handler for a field of neither layout fails too.
 *
 * @returns One line per schema change saying what became of it.
 */
async function cover(
  steps: Step[],
  files: Map<string, string>,
  problems: string[],
) {
  const lines: string[] = [];
  let layout = steps[0].schema!;
  for (const step of steps) {
    const target = step.schema ?? layout;
    let handlers: Record<string, unknown> = {};
    if (step.hasMigration) {
      const file = path.join(step.dir, "migration.ts");
      const module = await import(pathToFileURL(file).href);
      handlers = module.default.layout ?? {};
    }
    const stored = files.get(path.join(step.dir, "diff.json"));
    const diff: StoredDiff | undefined = stored && JSON.parse(stored);
    if (diff?.rewrite || Object.keys(handlers).length > 0) {
      try {
        const bytes = new Uint8Array(8);
        // eslint-disable-next-line no-new
        new Copier({
          bytes,
          from: layout,
          to: target,
          handlers: handlers as any,
        });
      } catch (error: any) {
        problems.push(`${relative(step.dir)}: ${error.message}`);
      }
    }
    if (diff) {
      const added = diff.changes.filter(
        (change) => change.kind === "field-added" && !change.obligation,
      );
      const lacking = added
        .filter((change) => !(change.path in handlers))
        .map((change) => change.path);
      const carried = diff.changes.filter(
        (change) =>
          change.kind === "field-moved" || change.kind === "default-changed",
      );
      const parts = [
        `${diff.obligations.length} decided by a handler`,
        `${carried.length} carried by the copier`,
        `${added.length - lacking.length} new fields filled in`,
      ];
      if (lacking.length > 0) {
        parts.push(`left for older files to lack: ${lacking.join(", ")}`);
      }
      lines.push(`  ${path.basename(step.dir)}: ${parts.join("; ")}`);
    }
    layout = target;
  }
  return lines;
}

async function check(args: string[]) {
  const problems: string[] = [];
  const steps = readSteps();
  if (steps.length === 0 || !steps[0].schema) {
    throw new Error("The oldest migration step has to carry a schema.");
  }

  const current = await describeSchema(currentSchema);
  const snapshot = [...steps].reverse().find((step) => step.schema)!;
  if (!same(snapshot.schema, current)) {
    problems.push(
      "flatbuffers/index.fbs changed since the newest migration. Run `yarn migration:new <slug>`.",
    );
  }

  for (const step of steps) {
    if (!step.schema) continue;
    const recorded = await describeSchema(path.join(step.dir, "schema.fbs"));
    if (!same(recorded, step.schema)) {
      problems.push(
        `${relative(step.dir)}: schema.json is not what schema.fbs compiles to.`,
      );
    }
  }

  const { files, rewrites } = await generate(steps);
  for (const [file, content] of files) {
    const actual = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (actual !== content) {
      problems.push(
        `${relative(file)} is out of date. Run \`yarn migration:sync\`.`,
      );
    }
    if (!file.endsWith("diff.json")) continue;
    const diff: StoredDiff = JSON.parse(content);
    if (!diff.conforms && !diff.rewrite) {
      problems.push(
        `${relative(file)}: flatc rejects the change as an evolution, but the diff found nothing breaking.`,
      );
    }
  }

  for (const step of steps) {
    if (rewrites.has(step.id) && !step.hasMigration) {
      problems.push(
        `${relative(step.dir)} changes the layout and has no migration.ts.`,
      );
    }
    const test = path.join(step.dir, "migration.test.ts");
    if (step.hasMigration && !fs.existsSync(test)) {
      problems.push(`${relative(step.dir)} has no migration.test.ts.`);
    }
    // What `migration:new` scaffolds is not a migration yet.
    for (const file of [path.join(step.dir, "migration.ts"), test]) {
      if (!fs.existsSync(file)) continue;
      const source = fs.readFileSync(file, "utf8");
      if (source.includes("TODO") || source.includes("test.todo(")) {
        problems.push(`${relative(file)} is still the scaffold.`);
      }
    }
  }

  const coverage = await cover(steps, files, problems);

  // Files are stamped with the newest id their writer knew, so a migration
  // merged with an id older than one already on the base branch would be
  // skipped by every file written in between.
  const base = args[args.indexOf("--base") + 1];
  if (args.includes("--base") && base) {
    const known = idsOn(base);
    const newest = known.sort()[known.length - 1];
    for (const step of steps) {
      if (newest && !known.includes(step.id) && step.id < newest) {
        problems.push(
          `${relative(step.dir)} is older than ${newest} on ${base}. Rename it with a current timestamp.`,
        );
      }
    }
  }

  if (problems.length > 0) {
    throw new Error(`Migrations:\n- ${problems.join("\n- ")}`);
  }
  for (const line of coverage) {
    console.log(line);
  }
  console.log(`Migrations: ${steps.length} steps, all covered.`);
}

const [command, ...rest] = process.argv.slice(2);
const commands: Record<string, (args: string[]) => Promise<void>> = {
  new: create,
  check,
  sync,
};

try {
  if (!commands[command]) {
    throw new Error("Usage: migration.ts <new|check|sync>");
  }
  await commands[command](rest);
} catch (error: any) {
  console.error(error.message);
  process.exit(1);
}
