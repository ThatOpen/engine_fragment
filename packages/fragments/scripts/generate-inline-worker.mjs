/**
 * Generates `dist/inline.mjs` — an opt-in side-effect module that embeds the
 * built worker as base64 and registers it via `FragmentsModels.registerInlineWorker`.
 *
 * Apps that import `@thatopen/fragments/inline` get the worker
 * inlined (works in IIFE / sandboxed iframes, no network). Apps that don't keep
 * today's bundle size and use the `import.meta.url` path.
 *
 * Run after the worker build (see the `build` script).
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const workerPath = resolve(root, "dist/Worker-inline/inline-worker.mjs");

if (!existsSync(workerPath)) {
  console.error(`Worker not found at ${workerPath}. Run the worker build first.`);
  process.exit(1);
}

const workerText = readFileSync(workerPath, "utf8");
if (/^\s*import[\s{]/m.test(workerText) || /from\s*["']\.\/[^"']+\.js["']/.test(workerText)) {
  console.error(
    "Inline worker is not self-contained (top-level import / chunk reference). It is loaded from a blob URL and cannot resolve chunks.",
  );
  process.exit(1);
}

const base64 = readFileSync(workerPath).toString("base64");
const out = `// AUTO-GENERATED by scripts/generate-inline-worker.mjs — do not edit.
import { FragmentsModels } from "./index.mjs";
FragmentsModels.registerInlineWorker(${JSON.stringify(base64)});
`;

writeFileSync(resolve(root, "dist/inline.mjs"), out);
console.log(`Generated dist/inline.mjs (${(base64.length / 1024 / 1024).toFixed(2)} MB base64)`);
